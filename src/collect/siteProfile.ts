function directOutcome(retrieval: Retrieval): string | null {
  return (retrieval.stages ?? []).find((s) => s.method === "direct fetch")?.outcome ?? null;
}

// The first fund phrase the site applies to itself (see BACKING_PREAMBLE).
function ownFundClaim(plain: string): RegExpExecArray | null {
  const re = new RegExp(FUND_SELF.source, "gi");
  let m: RegExpExecArray | null;
  let tries = 0;
  while ((m = re.exec(plain)) && tries++ < 8) {
    const before = plain.slice(Math.max(0, m.index - 60), m.index);
    if (!BACKING_PREAMBLE.test(before)) return m;
  }
  return null;
}

export function buildSiteProfile(input: ProfileInput): SiteProfile {
  const { retrieval, content, people } = input;
  let brand = brandOf(retrieval);
  const host = hostOf(retrieval.url);

  if (retrieval.status === "gap") {
    return {
      kind: "unclassified", kindEvidence: null, availability: "unavailable",
      availabilityNote: "ARGUS could not open or render the site. Nothing below is a claim about its content.",
      brand, selfDescription: null,
      summary: `${brand ?? host}: the site could not be opened, so ARGUS cannot say what it is.`,
      officialAccounts: [], linkedAccounts: [], people: [],
      nextStep: { kind: "none", reason: "Nothing was read from the page, so there is no account or contract to hand to a full investigation." },
      identitySignals: 0,
    };
  }

  const plain = content.replace(/!\[[^\]]*\]\([^)]*\)/g, " ");
  const thin = plain.length < 1500;

  // States that are not a project. Each is a real observation about the page.
  const wall = BOT_WALL.exec(plain);
  if (wall && plain.length < 2500) {
    return {
      kind: "blocked", kindEvidence: quoteAround(plain, wall.index, wall[0].length), availability: "blocked",
      availabilityNote: "The URL answered with a bot-protection challenge, not the site. ARGUS never saw the real page.",
      brand, selfDescription: null,
      summary: `${brand ?? host}: the page returned a bot-protection challenge (“${wall[0]}”), so ARGUS could not read the site.`,
      officialAccounts: [], linkedAccounts: [], people: [],
      nextStep: { kind: "none", reason: "A challenge page links nothing of the project's. Retry later or paste the project's account or contract directly." },
      identitySignals: 0,
    };
  }
  const parked = PARKED.exec(plain);
  if (parked && plain.length < 3500) {
    return {
      kind: "parked", kindEvidence: quoteAround(plain, parked.index, parked[0].length), availability: "parked",
      availabilityNote: "This is a domain parking / for-sale page. No project is being served at this URL.",
      brand, selfDescription: null,
      summary: `${host} is a parked domain (“${parked[0]}”). There is no project here to assess.`,
      officialAccounts: [], linkedAccounts: [], people: [],
      nextStep: { kind: "none", reason: "A parked domain links no project accounts. If a project claims this URL, that claim is the finding." },
      identitySignals: 0,
    };
  }
  const soon = COMING_SOON.exec(plain);
  if (soon && thin && people.length === 0) {
    const accounts = classifyAccounts(input.socials, retrieval, brand, people, content);
    return {
      kind: "coming-soon", kindEvidence: quoteAround(plain, soon.index, soon[0].length), availability: "coming-soon",
      availabilityNote: "A placeholder page. The site is live but shows no product, team, or documentation yet.",
      brand, selfDescription: selfDescriptionOf(plain, brand, retrieval.description),
      summary: `${brand ?? host} is a placeholder page (“${soon[0]}”). Nothing here can be verified yet.`,
      officialAccounts: accounts.official, linkedAccounts: accounts.linked, people: [],
      nextStep: nextStepOf(accounts.official, input.pivot, "coming-soon"),
      identitySignals: accounts.official.length ? 1 : 0,
    };
  }

  const availability: SiteAvailability = retrieval.status === "rendered"
    ? "live"
    : directOutcome(retrieval) === "spa-stub" ? "js-app" : "crawler-read";
  const availabilityNote = availability === "live"
    ? "Live. Server-rendered HTML was read directly."
    : availability === "js-app"
      ? "Live, but JavaScript-only: the server sends no content without a browser. ARGUS read it through the rendering crawler."
      : "Live. The direct fetch was blocked (cross-origin or network), so ARGUS read the page through the rendering crawler.";

  const selfDescription = selfDescriptionOf(plain, brand, retrieval.description);
  brand = refineBrand(brand, retrieval, selfDescription);
  const accounts = classifyAccounts(input.socials, retrieval, brand, people, content);

  let kind: SiteKind = "unclassified";
  let kindEvidence: string | null = null;
  const fundHit = ownFundClaim(plain);
  const studioHit = STUDIO_SELF.exec(plain);
  const contractOnPage = input.pivot?.attempted && input.pivot.method === "contract-on-page" && !!input.pivot.found;
  if (!input.isFund && (contractOnPage || (input.strongToken && input.tokenSignalCount >= 2))) {
    kind = "token-project";
    kindEvidence = contractOnPage
      ? `Links its token contract on the page (${input.pivot!.found!.symbol}).`
      : `Makes first-party token claims${input.pivot?.claim.ticker ? ` (${input.pivot.claim.ticker})` : ""}: tokenomics, supply, sale, or airdrop copy.`;
  } else if (fundHit && (input.isFund || fundHit.index < 4000)) {
    kind = "fund";
    kindEvidence = quoteAround(plain, fundHit.index, fundHit[0].length);
  } else if (studioHit) {
    kind = "studio";
    kindEvidence = quoteAround(plain, studioHit.index, studioHit[0].length);
  } else if (plain.length >= 400 && PRODUCT_CUE.test(plain)) {
    kind = "product";
    const cues = [...new Set((plain.match(new RegExp(PRODUCT_CUE.source, "gi")) ?? []).map((c) => c.toLowerCase()))].slice(0, 5);
    kindEvidence = `Product-site cues on the page: ${cues.join(", ")}.`;
  }

  const hasDocs = input.socials.some((s) => /github\.com\//i.test(s.url)) || /\b(?:docs|documentation|whitepaper|litepaper|gitbook)\b/i.test(plain);
  const identitySignals = (selfDescription ? 1 : 0) + (people.length ? 1 : 0) + (accounts.official.length ? 1 : 0) + (hasDocs ? 1 : 0);

  const who = brand ?? host;
  const summary = selfDescription
    ? `${who} says it is ${KIND_NOUN[kind]}: “${selfDescription}”`
    : `${who} reads as ${KIND_NOUN[kind]}, but the rendered page never says what it is in plain language.`;

  return {
    kind, kindEvidence, availability, availabilityNote, brand, selfDescription, summary,
    officialAccounts: accounts.official, linkedAccounts: accounts.linked, people,
    nextStep: nextStepOf(accounts.official, input.pivot, kind),
    identitySignals,
  };
}

/**
 * The profile for any recon, including records saved before profiles existed:
 * those are rebuilt from the stored retrieval, socials, and names, so an old
 * report still answers what-is-this / is-it-live / which-accounts-are-official.
 */
export function profileOf(recon: Recon): SiteProfile {
  if (recon.profile) return recon.profile;
  const people: NamedPerson[] = recon.team.people ?? recon.team.names.map((name) => ({ name, role: null, basis: "inline-role" as const }));
  const content = recon.retrieval.content ?? "";
  return buildSiteProfile({
    retrieval: recon.retrieval,
    socials: recon.socials,
    people,
    isFund: !!recon.isFund,
    strongToken: STRONG_TOKEN.test(content),
    tokenSignalCount: recon.tokenSignals.length,
    content,
    pivot: recon.pivot,
  });
}

function nextStepOf(official: SiteAccount[], pivot: OnChainPivot | undefined, kind: SiteKind): NextStep {
  if (pivot?.attempted && pivot.method === "contract-on-page" && pivot.found) {
    return {
      kind: "token", ref: pivot.found.address,
      label: `Open the full token audit for ${pivot.found.symbol}`,
      reason: "The page links this contract itself, so the on-chain audit is bound to this site.",
    };
  }
  const x = official.find((a) => a.platform === "x" && a.handle);
  if (x?.handle) {
    return {
      kind: "handle", ref: `@${x.handle}`,
      label: `Run full ARGUS on @${x.handle}`,
      reason: `${x.why} A full account investigation resolves the people and history behind it.`,
    };
  }
  const base = kind === "fund"
    ? "No official X account is linked on the page, so there is no account to hand to a full investigation."
    : "No official X account or token contract is linked on the rendered page, so ARGUS will not launch a scan it cannot bind.";
  return { kind: "none", reason: `${base} Paste the account or contract to investigate it directly.` };
}
