// The first-pass answer a pasted URL owes the analyst, built only from what
// ARGUS actually rendered plus the first-party links on that page:
//
//   1. what this is (fund, token project, product, studio, parked, blocked,
//      coming soon), with the phrase the site used to say so;
//   2. whether the site is live, JavaScript-only, read through the crawler,
//      parked, behind a bot wall, or unavailable;
//   3. which linked accounts are the project's OWN (host or brand affinity, a
//      first-party cue, or the only account of its kind on the page) versus
//      accounts the page merely links (a portfolio company, a partner, a
//      person's own profile);
//   4. one plain-language line: who they say they are;
//   5. the one next step that is actually bound by the page. No button ever
//      launches a scan on a handle or contract the page did not link.
//
// Everything is deterministic and keyless. Nothing here is fetched.
import type { NamedPerson } from "./roster";
import type { Retrieval } from "./retrieve";
