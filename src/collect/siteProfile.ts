// Strong, first-party evidence that THIS site is the token project (not just
// keyword noise): an explicit token launch/economics claim or a $-ticker/contract.
export const STRONG_TOKEN = /\b(tokenomics|total supply|circulating supply|max supply|\bTGE\b|fair launch|token sale|presale|airdrop|buy \$?[A-Z]{2,8}\b|our token)\b|0x[a-fA-F0-9]{40}/i;

export type SiteKind = "fund" | "token-project" | "product" | "studio" | "parked" | "blocked" | "coming-soon" | "unclassified";
export type SiteAvailability = "live" | "js-app" | "crawler-read" | "parked" | "blocked" | "coming-soon" | "unavailable";
export type SocialPlatform = "x" | "telegram" | "discord" | "github" | "linkedin" | "youtube" | "medium" | "farcaster" | "instagram" | "other";
export type AccountBasis = "host-match" | "brand-match" | "first-party-cue" | "sole-link" | "linked" | "person-profile";

export interface SiteAccount {
  platform: SocialPlatform;
  label: string;
  url: string;
  handle: string | null;
  basis: AccountBasis;
  /** Plain-language reason the account is or is not counted as the project's own. */
  why: string;
}

export type NextStep =
  | { kind: "token"; ref: string; label: string; reason: string }
  | { kind: "handle"; ref: string; label: string; reason: string }
  | { kind: "none"; reason: string };

export interface SiteProfile {
  kind: SiteKind;
  /** The site's own words that drove the classification, or null. */
  kindEvidence: string | null;
  availability: SiteAvailability;
  availabilityNote: string;
  brand: string | null;
  /** The sentence in which the site says what it is, verbatim, or null. */
  selfDescription: string | null;
  /** One plain-language line: what this is, in the site's own terms. */
  summary: string;
  officialAccounts: SiteAccount[];
  linkedAccounts: SiteAccount[];
  people: NamedPerson[];
  nextStep: NextStep;
  /** Distinct first-party identity signals present: self-description, named people, official accounts, docs/code. */
  identitySignals: number;
}

export interface ProfileInput {
  retrieval: Retrieval;
  socials: { label: string; url: string }[];
  people: NamedPerson[];
  isFund: boolean;
  strongToken: boolean;
  tokenSignalCount: number;
  content: string;
  pivot?: OnChainPivot;
}

