// "Backed by leading venture capital firms" is a token project describing its
// investors, not a fund describing itself. Fund phrases a backing preamble
// introduces are skipped; the first one the site applies to itself counts.
const BACKING_PREAMBLE = /(?:backed|supported|funded|invested|financed) by|investors? (?:include|such as|like)|our (?:investors|backers|partners)|raised (?:from|by)|partners? (?:include|such as)|led by|with support from/i;

// The broad fund gate that decides whether a site is reality-checked as a
// token at all. Kept broad on purpose: a fund must never be judged by a random
// same-ticker DEX coin. The one carve-out is a backing preamble, because
// "backed by leading venture capital firms" is a token project's investor line,
// not a fund describing itself, and it was suppressing the on-chain check.
const FUND_SITE = /\b(venture capital|ventures\b|\bvc\b|\bfund\b|\bfunds\b|capital\b|investment (?:firm|fund|dao)|portfolio compan|we (?:invest|back)|backing founders|accelerator|incubator|advisory|angel (?:investor|fund)|research (?:collective|studio))\b/i;

export function selfDescribesAsFund(content: string, title?: string | null): boolean {
  if (title && FUND_SITE.test(title)) return true;
  const re = new RegExp(FUND_SITE.source, "gi");
  let m: RegExpExecArray | null;
  let tries = 0;
  while ((m = re.exec(content)) && tries++ < 12) {
    const before = content.slice(Math.max(0, m.index - 60), m.index);
    if (!BACKING_PREAMBLE.test(before)) return true;
  }
  return false;
}
const STUDIO_SELF = /\b(?:venture studio|design studio|development studio|web3 studio|product studio|creative studio|(?:digital|software|blockchain|web3|crypto|marketing|design) agency|we build products|(?:software|blockchain|smart[- ]contract) (?:development|consultancy|consulting)|dev shop|we help (?:teams|companies|founders) (?:build|launch|ship))\b/i;
const PRODUCT_CUE = /\b(?:launch app|open app|get started|sign up|start (?:free|building)|pricing|download|api|docs|documentation|dashboard|platform|protocol|wallet|exchange|marketplace|app store|google play|integrations?|sdk|mainnet|testnet|bridge|swap|stake)\b/i;

const NOISE_SENTENCE = /cookie|javascript|browser|privacy policy|terms of|all rights reserved|©|registered trademark|\btrademarks?\b|member (?:of )?finra|securities transactions|not (?:an offer|investment advice)|for informational purposes/i;

function hostOf(url: string): string {
  try { return new URL(url).hostname.replace(/^www\./i, "").toLowerCase(); } catch { return url.toLowerCase(); }
}

const key = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, "");

/** The brand, from the title's first segment when it is short enough to be a name; else the host label. */
export function brandOf(retrieval: Retrieval): string | null {
  const title = (retrieval.title ?? "").replace(/\s+/g, " ").trim();
  const seg = title.split(/\s+[|–—:·]\s+|\s+-\s+/)[0]?.trim() ?? "";
  if (seg.length >= 2 && seg.length <= 40 && !/[.!?]$/.test(seg) && seg.split(" ").length <= 6) return seg;
  const host = hostOf(retrieval.url);
  const label = host.split(".")[0] ?? "";
  return label.length >= 2 ? label : null;
}

// When the title gave nothing usable and the page opens "10X Capital is a…",
// the subject of that sentence is the brand as the site writes it, provided it
// agrees with the host label. Presentation only; matching still uses the key.
function refineBrand(brand: string | null, retrieval: Retrieval, selfDescription: string | null): string | null {
  if (!selfDescription) return brand;
  const hostKey = key(hostOf(retrieval.url).split(".")[0] ?? "");
  if (brand && key(brand) !== hostKey) return brand;
  const subject = selfDescription.match(/^(.{2,40}?)\s+(?:is|are|builds|provides|helps|offers|enables|brings|makes|lets|powers|invests|backs|delivers|connects)\b/i)?.[1]?.trim();
  if (!subject) return brand;
  const k = key(subject);
  return k.length >= 3 && (k === hostKey || hostKey.includes(k) || k.includes(hostKey)) ? subject : brand;
}

// The sentence (or clause) the match sits in, snapped to the nearest sentence
// or line boundary so a quote does not begin mid-heading.
function quoteAround(content: string, index: number, length: number, pad = 110): string {
  const lo = Math.max(0, index - pad);
  const before = content.slice(lo, index);
  const boundary = Math.max(before.lastIndexOf(". "), before.lastIndexOf("\n"), before.lastIndexOf("! "), before.lastIndexOf("? "));
  const start = boundary >= 0 ? lo + boundary + (before[boundary] === "\n" ? 1 : 2) : lo;
  const hi = Math.min(content.length, index + length + pad);
  const after = content.slice(index + length, hi);
  const stop = after.search(/[.!?](?:\s|$)|\n/);
  const end = stop >= 0 ? index + length + stop + (after[stop] === "\n" ? 0 : 1) : hi;
  let q = content.slice(start, end).replace(/[\s*#>]+/g, " ").trim();
  if (boundary < 0 && lo > 0) q = "…" + q;
  if (stop < 0 && hi < content.length) q = q + "…";
  return q.length > 180 ? q.slice(0, 177).replace(/\s+\S*$/, "") + "…" : q;
}

/**
 * The sentence in which the site says what it is. Preference: a sentence that
 * opens with the brand and predicates it ("10X Capital is a next-generation
 * merchant bank…"); then the page's own meta description; then the first
 * "is a / are the" sentence near the top. Never a synthesized paraphrase.
 */
export function selfDescriptionOf(content: string, brand: string | null, description?: string | null): string | null {
  const head = content.slice(0, 6000)
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/^[\s#*>-]+/gm, "")
    .replace(/[*_]{1,3}/g, "");
  const sentences = head.split(/(?<=[.!?])\s+|\n+/).map((s) => s.replace(/\s+/g, " ").trim()).filter((s) => s.length >= 25 && s.length <= 240 && !NOISE_SENTENCE.test(s));
  const brandKey = brand ? key(brand) : "";
  const PREDICATE = /\b(?:is|are|builds|provides|helps|offers|enables|brings|makes|lets|powers|invests|backs|delivers|connects)\b/i;
  if (brandKey.length >= 3) {
    const own = sentences.find((s) => key(s.slice(0, brand!.length + 4)).startsWith(brandKey) && PREDICATE.test(s));
    if (own) return own;
  }
  const meta = (description ?? "").replace(/\s+/g, " ").trim();
  if (meta.length >= 25) return meta.length > 240 ? meta.slice(0, 237).replace(/\s+\S*$/, "") + "…" : meta;
  const generic = sentences.slice(0, 40).find((s) => /\b(?:is|are) (?:a|an|the)\b/i.test(s) && /^[A-Z0-9]/.test(s));
  return generic ?? null;
}

// ---- accounts ----
const X_NOISE = /^(?:status|home|intent|share|i|hashtag|search|explore|login|signup|settings|messages|notifications|compose|privacy|tos)$/i;
const TG_NOISE = /^(?:share|joinchat|addstickers|proxy|s)$/i;
const GH_NOISE = /^(?:orgs|sponsors|topics|features|about|marketplace|explore|pricing|login|join|settings|apps|site)$/i;

export function classifyAccountUrl(url: string): { platform: SocialPlatform; handle: string | null; personProfile: boolean } {
  let u: URL;
  try { u = new URL(url); } catch { return { platform: "other", handle: null, personProfile: false }; }
  const host = u.hostname.replace(/^www\./i, "").toLowerCase();
  const segs = u.pathname.split("/").filter(Boolean);
  const first = segs[0] ?? "";
  if (host === "x.com" || host === "twitter.com" || host === "mobile.twitter.com") {
    const h = first.replace(/^@/, "");
    return { platform: "x", handle: h && !X_NOISE.test(h) && /^[A-Za-z0-9_]{2,30}$/.test(h) ? h : null, personProfile: false };
  }
  if (host === "t.me" || host === "telegram.me") {
    const h = first.replace(/^@/, "");
    return { platform: "telegram", handle: h && !TG_NOISE.test(h) && /^[A-Za-z0-9_]{3,40}$/.test(h) ? h : null, personProfile: false };
  }
  if (host === "discord.gg" || host === "discord.com" || host === "discordapp.com") {
    return { platform: "discord", handle: null, personProfile: false };
  }
  if (host === "github.com") {
    return { platform: "github", handle: first && !GH_NOISE.test(first) ? first : null, personProfile: false };
  }
  if (host === "linkedin.com" || host.endsWith(".linkedin.com")) {
    if (first === "company" || first === "school") return { platform: "linkedin", handle: segs[1] ?? null, personProfile: false };
    return { platform: "linkedin", handle: first === "in" ? segs[1] ?? null : null, personProfile: first === "in" };
  }
  if (host === "youtube.com" || host === "youtu.be") {
    const h = first.startsWith("@") ? first.slice(1) : first === "c" || first === "channel" || first === "user" ? segs[1] ?? null : null;
    return { platform: "youtube", handle: h, personProfile: false };
  }
  if (host === "medium.com" || host.endsWith(".medium.com")) {
    const sub = host.endsWith(".medium.com") ? host.replace(/\.medium\.com$/, "") : null;
    return { platform: "medium", handle: first.startsWith("@") ? first.slice(1) : sub, personProfile: false };
  }
  if (host === "warpcast.com" || host === "farcaster.xyz") return { platform: "farcaster", handle: first || null, personProfile: false };
  if (host === "instagram.com") return { platform: "instagram", handle: first || null, personProfile: false };
  return { platform: "other", handle: null, personProfile: false };
}

const PLATFORM_LABEL: Record<SocialPlatform, string> = {
  x: "X", telegram: "Telegram", discord: "Discord", github: "GitHub", linkedin: "LinkedIn",
  youtube: "YouTube", medium: "Medium", farcaster: "Farcaster", instagram: "Instagram", other: "link",
};

function affinity(handle: string, hostKey: string, brandKey: string): "host-match" | "brand-match" | null {
  const h = key(handle);
  if (h.length < 3) return null;
  const near = (a: string, b: string) => a === b || (a.length >= 4 && b.includes(a)) || (b.length >= 4 && a.includes(b));
  if (hostKey.length >= 4 && near(h, hostKey)) return "host-match";
  if (brandKey.length >= 4 && brandKey !== hostKey && near(h, brandKey)) return "brand-match";
  return null;
}

function looksLikePerson(handle: string, people: NamedPerson[]): boolean {
  const h = key(handle);
  if (h.length < 4) return false;
  return people.some((p) => {
    const parts = p.name.split(/\s+/).map(key).filter(Boolean);
    const first = parts[0] ?? "";
    const last = parts[parts.length - 1] ?? "";
    return h === key(p.name) || (last.length >= 5 && h.includes(last)) || (first.length >= 3 && last.length >= 3 && h.includes(first) && h.includes(last));
  });
}

const CUE = /follow(?:\s+us)?(?:\s+on)?|official(?:\s+account)?|our (?:x|twitter|telegram|discord|github|linkedin)|join (?:our|the) (?:community|telegram|discord)|community/i;

function hasCue(url: string, handle: string | null, content: string): boolean {
  const target = handle ? handle : url;
  const esc = target.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?:${CUE.source})[^\\n]{0,40}${esc}`, "i").test(content);
}

export function classifyAccounts(
  socials: { label: string; url: string }[],
  retrieval: Retrieval,
  brand: string | null,
  people: NamedPerson[],
  content: string,
): { official: SiteAccount[]; linked: SiteAccount[] } {
  const hostKey = key(hostOf(retrieval.url).split(".")[0] ?? "");
  const brandKey = brand ? key(brand) : "";
  const rows = socials.map((s) => ({ ...s, ...classifyAccountUrl(s.url) }));
  const perPlatform = new Map<SocialPlatform, number>();
  for (const r of rows) perPlatform.set(r.platform, (perPlatform.get(r.platform) ?? 0) + 1);

  const official: SiteAccount[] = [];
  const linked: SiteAccount[] = [];
  for (const r of rows) {
    const label = r.handle ? (r.platform === "x" ? `@${r.handle}` : `${PLATFORM_LABEL[r.platform]} · ${r.handle}`) : PLATFORM_LABEL[r.platform] + (r.platform === "discord" ? " invite" : "");
    const base = { platform: r.platform, label, url: r.url, handle: r.handle };
    if (r.personProfile) {
      linked.push({ ...base, basis: "person-profile", why: "A personal profile, not the project's account." });
      continue;
    }
    // A named person's own handle can contain the brand ("samclutchfield" on
    // clutch.example); the person wins, because the page named them.
    if (r.handle && looksLikePerson(r.handle, people)) {
      linked.push({ ...base, basis: "person-profile", why: "Looks like a named team member's own account, not the project's." });
      continue;
    }
    const aff = r.handle ? affinity(r.handle, hostKey, brandKey) : null;
    if (aff) {
      official.push({ ...base, basis: aff, why: aff === "host-match" ? "Matches the site's own domain." : `Matches the site's brand name (${brand}).` });
      continue;
    }
    if (hasCue(r.url, r.handle, content)) {
      official.push({ ...base, basis: "first-party-cue", why: "The page frames it as its own (follow us / official / join our community)." });
      continue;
    }
    if ((perPlatform.get(r.platform) ?? 0) === 1 && r.platform !== "other") {
      official.push({ ...base, basis: "sole-link", why: `The only ${PLATFORM_LABEL[r.platform]} account the page links.` });
      continue;
    }
    linked.push({ ...base, basis: "linked", why: `One of several ${PLATFORM_LABEL[r.platform]} accounts on the page; the site does not claim it as its own.` });
  }
  return { official, linked };
}

